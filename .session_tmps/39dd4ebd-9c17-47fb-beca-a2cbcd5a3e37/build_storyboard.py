def vo_for(start, end):
    """Return narration overlapping [start,end], else '无'."""
    parts = [txt for ts, txt in vo_lines if start - 2.0 <= ts < end + 0.5]
    if not parts:
        # find the line active at start
        active = [txt for ts, txt in vo_lines if ts <= start]
        if active:
            return active[-1]
        return "无"
    joined = " ".join(parts)
    return joined if len(joined) <= 160 else joined[:157] + "…"

