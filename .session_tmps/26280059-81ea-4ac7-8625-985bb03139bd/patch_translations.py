def apply_patch(filepath, patch_dict):
    """Apply a translation patch to a .strings file."""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    patched_count = 0
    for key, new_value in patch_dict.items():
        # Escape special regex chars in the key
        escaped_key = re.escape(key)
        # Match: "key" = "old_value";
        pattern = r'"' + escaped_key + r'"\s*=\s*"(?:[^"\\]|\\.)*"\s*;'
        replacement = '"' + key + '" = "' + new_value + '";'
        new_content, n = re.subn(pattern, replacement, content, count=1)
        if n > 0:
            content = new_content
            patched_count += 1

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)

    return patched_count

